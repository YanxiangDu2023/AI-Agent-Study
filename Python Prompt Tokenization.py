# 这一节主要讲两件事：**怎么向模型提出要求，以及模型怎么从候选 token 中选出输出。** 我们接着你前面理解的“给各个 token 打分”来讲。

# **1. Temperature、Top-k、Top-p：控制下一个 token 怎么选**

# 假设输入：

# > 今天的天气很适合去……

# 模型会给词表里的 token 打分，再用 Softmax 将分数转换成概率。为了方便理解，假设只有下面五个候选：

# | 候选 token | 概率 |
# |---|---:|
# | 散步 | 50% |
# | 跑步 | 25% |
# | 游泳 | 15% |
# | 购物 | 8% |
# | 睡觉 | 2% |

# **这些是下一个位置的候选，并不是模型已经写好了五个词。** 模型从中选择一个，加入原文，再预测下一个 token。

# 三个参数，就是在影响这次选择。

# **① Temperature：调整概率之间的差距**

# - **低温度**：让热门候选更占优势，例如“散步”变得更容易被选中。
# - **高温度**：缩小候选之间的概率差距，让“购物”“睡觉”等也更有机会被选中。
# - **温度为 1**：保持原来的 Softmax 分布。

# 你可以理解为：

# > 低温度更倾向于常见答案，高温度更愿意尝试其他答案。

# 公式里的 \(z_i\) 是模型给第 \(i\) 个 token 的原始分数，\(T\) 是温度。**先把分数除以 \(T\)，再用 Softmax 转成概率。**

# 注意：**低温度不等于事实更准确。** 如果模型本来就倾向于一个错误答案，低温度也可能让它更稳定地输出这个错误答案。

# **② Top-k：只让前 k 名参加抽选**

# 例如 `Top-k = 3`，只保留：

# | 保留候选 | 原概率 | 重新归一化后 |
# |---|---:|---:|
# | 散步 | 50% | 约 55.6% |
# | 跑步 | 25% | 约 27.8% |
# | 游泳 | 15% | 约 16.7% |

# “购物”和“睡觉”直接被排除。

# 为什么要重新归一化？因为保留下来的概率之和只有 90%，需要除以 90%，让总和重新变成 100%。

# > **Top-k 固定的是候选数量。**

# 当 `k = 1` 时，只剩“散步”，就直接选它。这叫**贪心解码**。

# **③ Top-p：保留累计概率达到阈值的候选**

# 例如 `Top-p = 0.8`，从概率最大的开始累加：

# - 散步：累计 50%，不够。
# - 加上跑步：累计 75%，还不够。
# - 加上游泳：累计 90%，达到 80%，停止。

# 所以保留前三个，再归一化并抽选。

# 这里不是要求“每个 token 的概率超过 80%”，而是要求**保留下来的 token，概率加起来达到 80%**。

# > **Top-p 固定的是累计概率门槛，候选数量可以变化。**

# 如果“散步”本身就占 85%，那么 `Top-p = 0.8` 就只保留它。

# 这三个参数可以这样记：

# | 参数 | 作用 |
# |---|---|
# | Temperature | 调整候选之间的概率差距 |
# | Top-k | 只保留概率最高的 k 个 |
# | Top-p | 保留累计概率达到 p 的最小一组 |

# 原文中有两处不要理解得太绝对：**三个参数的应用顺序取决于具体实现**；顺序过滤时可能重新归一化，所以也不能一概理解为两个独立候选集合的交集。另外，`Temperature = 0` 通常是程序用来表示贪心选择的特殊设置，不能直接代入除以 \(T\) 的公式。

