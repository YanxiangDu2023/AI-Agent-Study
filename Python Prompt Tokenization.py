# **5. 思维链提示：让复杂问题按步骤处理**

# 对于一道需要多步计算的题，你可以要求：

# ```text
# 请分步骤计算，并给出关键计算过程。
# ```

# 例如原文的篮球题，关键计算就是：

# ```text
