import re, collections

def get_stats(vocab):
    """统计词元对频率"""
    pairs = collections.defaultdict(int)
    for word, freq in vocab.items():
        symbols = word.split()
        for i in range(len(symbols)-1):
            pairs[symbols[i],symbols[i+1]] += freq
    return pairs


# 如果传入的是原来的数据：

# ```python
# vocab = {
#     'h u g </w>': 1,
#     'p u g </w>': 1,
#     'p u n </w>': 1,
#     'b u n </w>': 1
# }
# ```

# **四个单词全部循环完后，返回的 `pairs` 内容是：**

# ```python
# {
#     ('h', 'u'): 1,
#     ('u', 'g'): 2,
#     ('g', '</w>'): 2,
#     ('p', 'u'): 2,
#     ('u', 'n'): 2,
#     ('n', '</w>'): 2,
#     ('b', 'u'): 1
# }
# ```

# 每一项的来源是：

# | 相邻的一对 | 在哪些词里出现 | 总次数 |
# |---|---|---:|
# | `h` 和 `u` | hug | 1 |
# | `u` 和 `g` | hug、pug | 2 |
# | `g` 和 `</w>` | hug、pug | 2 |
# | `p` 和 `u` | pug、pun | 2 |
# | `u` 和 `n` | pun、bun | 2 |
# | `n` 和 `</w>` | pun、bun | 2 |
# | `b` 和 `u` | bun | 1 |

# **`pairs` 在循环外创建，所以每处理一个单词，都会在同一个字典里累加，不会清零。**

# 最后：

# ```python
# return pairs
# ```

# 把这个统计结果返回。此时只是**数完次数，还没有合并任何片段**。



def merge_vocab(pair, v_in):
    """合并词元对"""
    v_out = {}
    bigram = re.escape(' '.join(pair))
    p = re.compile(r'(?<!\S)' + bigram + r'(?!\S)')
    
    for word in v_in:
        # word = 'h u g </w>'
        w_out = p.sub(''.join(pair), word)
        
# p.sub(替换成什么, 在哪个字符串里替换)

        
# 所以这行的意思是：
# 在 'h u g </w>' 里面，把 'u g' 替换成 'ug'。
# 得到 w_out = 'h ug </w>'
        
    
        v_out[w_out] = v_in[word]
        
# 第四步：把新单词和原来的次数存进去。
# v_out[w_out] = v_in[word]

# 代入变量，就是：
# v_out['h ug </w>'] = v_in['h u g </w>']

# 右边查到的次数是 1，所以相当于：
# v_out['h ug </w>'] = 1

# 现在新字典是：
# v_out = {    'h ug </w>': 1}


    return v_out



# 准备语料库，每个词末尾加上</w>表示结束，并切分好字符
vocab = {'h u g </w>': 1, 'p u g </w>': 1, 'p u n </w>': 1, 'b u n </w>': 1}
num_merges = 4 # 设置合并次数



for i in range(num_merges):
    pairs = get_stats(vocab)
    if not pairs:
        break
    best = max(pairs, key=pairs.get)
    # best = ('u', 'g')
    vocab = merge_vocab(best, vocab)
    print(f"第{i+1}次合并: {best} -> {''.join(best)}")
    print(f"新词表（部分）: {list(vocab.keys())}")
    print("-" * 20)

